import type { AgeStage, Availability, Product, ProductVariant } from '../types'

const DIAPER_SIZES = {
  RN: { detail: 'Hasta 4,5 kg', kg: [0, 4.5] as [number, number] },
  P: { detail: '3 a 6 kg', kg: [3, 6] as [number, number] },
  M: { detail: '6 a 10 kg', kg: [6, 10] as [number, number] },
  G: { detail: '9 a 13 kg', kg: [9, 13] as [number, number] },
  XG: { detail: '12 a 16 kg', kg: [12, 16] as [number, number] },
  XXG: { detail: 'Más de 14 kg', kg: [14, 25] as [number, number] },
}
type DiaperSize = keyof typeof DIAPER_SIZES

function sizes(
  base: string,
  rows: Array<[DiaperSize, number, number, Availability?]>,
): ProductVariant[] {
  return rows.map(([size, units, price, availability = 'in_stock']) => ({
    id: `${base}-${size.toLowerCase()}`,
    sku: `${base.toUpperCase()}-${size}`,
    label: size,
    detail: `${DIAPER_SIZES[size].detail} · ${units} u.`,
    option: { name: 'Talle', value: size },
    price,
    availability,
    weightRangeKg: DIAPER_SIZES[size].kg,
  }))
}

function simple(
  base: string,
  name: string,
  rows: Array<[label: string, detail: string | undefined, price: number, availability?: Availability, swatch?: string]>,
): ProductVariant[] {
  return rows.map(([label, detail, price, availability = 'in_stock', swatch]) => ({
    id: `${base}-${label.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
    sku: `${base.toUpperCase()}-${label.toUpperCase().replace(/[^A-Z0-9]+/g, '')}`,
    label,
    detail,
    option: { name, value: label },
    price,
    availability,
    swatch,
  }))
}

